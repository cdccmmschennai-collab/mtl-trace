"""CDC MTL Tool — desktop launcher.

Double-click the packaged `CDC MTL Tool.exe` (built from this file, see `build_exe.ps1`), or run
`.venv\\Scripts\\python desktop.py` from a checkout after `npm --prefix frontend run build`.

It starts the local engine on a free 127.0.0.1 port, opens the tool in its own window (Microsoft Edge
WebView2, part of Windows 10/11), and stops everything when the window is closed. Every launch starts with an
empty session: no history is kept. Working data lives in %LOCALAPPDATA%\\CDC MTL Tool (packaged) or
<repo>\\MTL_DATA (checkout); nothing leaves the machine.
"""

import ctypes
import os
import socket
import sys
import threading
import time
import traceback
import urllib.request
from pathlib import Path, PurePath

APP_NAME = "CDC MTL Tool"
WINDOW_TITLE = "MTL Trace"
_MUTEX_NAME = "Local\\CDC-MTL-Tool-single-instance"


def _message_box(text: str, error: bool = True) -> None:
    flags = 0x10 if error else 0x40                       # MB_ICONERROR / MB_ICONINFORMATION
    ctypes.windll.user32.MessageBoxW(None, text, APP_NAME, flags)


def _single_instance():
    """Hold a named mutex for the app's lifetime. Two copies would share (and reset) one session."""
    handle = ctypes.windll.kernel32.CreateMutexW(None, False, _MUTEX_NAME)
    if ctypes.windll.kernel32.GetLastError() == 183:      # ERROR_ALREADY_EXISTS
        return None
    return handle


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _log_path() -> Path:
    base = Path(os.environ.get("LOCALAPPDATA") or Path.home()) / APP_NAME
    base.mkdir(parents=True, exist_ok=True)
    return base / "desktop.log"


class DesktopApi:
    """Exposed to the page as `window.pywebview.api`. Names starting with `_` stay private."""

    def __init__(self, base_url: str):
        self._base_url = base_url
        self._window = None

    def save_file(self, url: str, file_name: str) -> str | None:
        """Show "Save as", then write the generated file there. Returns the saved path, or None if cancelled."""
        if not url.startswith("/api/"):
            raise ValueError("Only files generated by the tool can be saved.")
        import webview

        suffix = PurePath(file_name).suffix.lower()
        types = ("Excel workbook (*.xlsx)",) if suffix == ".xlsx" else ("CSV file (*.csv)",) if suffix == ".csv" else ()
        chosen = self._window.create_file_dialog(webview.FileDialog.SAVE, save_filename=file_name,
                                                 file_types=(*types, "All files (*.*)"))
        if not chosen:
            return None
        target = Path(chosen if isinstance(chosen, str) else chosen[0])
        if suffix and not target.suffix:
            target = target.with_suffix(suffix)
        with urllib.request.urlopen(self._base_url + url, timeout=120) as resp:
            data = resp.read()
        tmp = target.with_name(target.name + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, target)
        return str(target)


def main() -> int:
    # A windowed executable has no console: give libraries that write to stdout/stderr somewhere to write.
    if sys.stdout is None or sys.stderr is None:
        sink = open(_log_path(), "a", encoding="utf-8", buffering=1)
        sys.stdout = sys.stdout or sink
        sys.stderr = sys.stderr or sink

    mutex = _single_instance()
    if mutex is None:
        _message_box(f"{APP_NAME} is already open.", error=False)
        return 0

    os.environ.setdefault("MTL_FRESH_START", "1")          # every launch starts a new, empty session

    import uvicorn
    import webview

    from backend.main import create_app

    app = create_app()
    port = _free_port()
    base_url = f"http://127.0.0.1:{port}"
    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_config=None, access_log=False))
    thread = threading.Thread(target=server.run, name="engine", daemon=True)
    thread.start()

    deadline = time.monotonic() + 30
    while not server.started:
        if not thread.is_alive() or time.monotonic() > deadline:
            _message_box(f"{APP_NAME} could not start its local engine on port {port}.\n\nSee {_log_path()}")
            return 1
        time.sleep(0.05)

    api = DesktopApi(base_url)
    window = webview.create_window(WINDOW_TITLE, base_url, js_api=api, width=1360, height=900,
                                   min_size=(980, 640), text_select=True)
    api._window = window
    try:
        webview.start()                                     # returns when the window is closed
    finally:
        server.should_exit = True
        thread.join(timeout=10)
        app.state.db.dispose()
        ctypes.windll.kernel32.CloseHandle(mutex)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:
        with open(_log_path(), "a", encoding="utf-8") as f:
            f.write(traceback.format_exc())
        _message_box(f"{APP_NAME} stopped because of an unexpected error.\n\nDetails were written to {_log_path()}")
        sys.exit(1)
